"""Turn the sport-mode recordings into FixStand / FixSquat keyframes (ts, qs) for unitree_cpp_deploy State_Fix.

Each stand-up / sit-down in the CSVs is cut out (onset: any |dq| > 0.15 rad/s, end: every joint within 0.01 rad of its
final value), aligned where the calves are half-way, averaged over all cycles, and sampled every --dt seconds.
  python3 extract_keyframes.py data/*.csv.gz [--dt 0.04] [--out fix_states.yaml] [--npz sport_motion.npz]
fix_states.yaml holds the FixStand / FixSquat blocks for unitree_cpp_deploy-config.yaml."""
import sys
from argparse import ArgumentParser
import numpy as np, pandas as pd

LEGS, JOINTS = ["FR", "FL", "RR", "RL"], ["hip", "thigh", "calf"]
QC = [f"q_{l}_{j}" for l in LEGS for j in JOINTS]
DC = [c.replace("q_", "dq_") for c in QC]
TC = [c.replace("q_", "tau_") for c in QC]

p = ArgumentParser()
p.add_argument("csv", nargs="+"); p.add_argument("--dt", type=float, default=0.04)
p.add_argument("--out", default="fix_states.yaml"); p.add_argument("--npz", default="sport_motion.npz")
p.add_argument("--lead", type=float, default=0.5, help="blend from the command at entry onto the recorded start pose")
p.add_argument("--tail", type=float, default=0.3, help="hold the final pose this long (FixSquat -> Passive happens after it)")
p.add_argument("--ramp", type=float, default=0.3, help="gain_ramp_s")
args = p.parse_args()


def cut(d):
    """yield (kind, q[n,12], tau[n,12]) at 500 Hz for each full stand-up / sit-down"""
    t, q, dq, tau = d.t.values, d[QC].values, d[DC].values, d[TC].values
    moving = np.abs(dq).max(1) > 0.15
    calf = q[:, [2, 5, 8, 11]].mean(1)
    i = 0
    while i < len(t):
        if not moving[i]: i += 1; continue
        s = i
        # extend while the robot is still travelling between the two poses
        e = s
        while e + 1 < len(t) and (moving[e + 1] or t[e + 1] - t[e] < 0.002 or np.abs(q[e + 1] - q[min(e + 250, len(t) - 1)]).max() > 0.01):
            e += 1
            if np.abs(q[e] - q[min(e + 250, len(t) - 1)]).max() < 0.01 and not moving[e]: break
        if abs(calf[e] - calf[s]) > 1.0:  # a real posture change (lying calf -2.8 <-> standing -1.38)
            yield ("up" if calf[e] > calf[s] else "down"), q[s:e + 1], tau[s:e + 1]
        i = e + 1


segs = {"up": [], "down": []}
for fn in args.csv:
    for kind, q, tau in cut(pd.read_csv(fn)):
        segs[kind].append((q, tau)); print(f"{fn}: {kind:4} {len(q) / 500:.2f} s", file=sys.stderr)

out = {}
for kind, lst in segs.items():
    # align at the moment the mean calf is half-way between the two poses (onset detection jitters on small twitches),
    # keep the shortest lead-in / tail common to every cycle
    mids = []
    for q, _ in lst:
        c = q[:, [2, 5, 8, 11]].mean(1); half = 0.5 * (c[0] + c[-1])
        mids.append(int(np.argmax(c > half) if kind == "up" else np.argmax(c < half)))
    pre = min(mids); post = min(len(q) - m for (q, _), m in zip(lst, mids))
    Q = np.stack([q[m - pre:m + post] for (q, _), m in zip(lst, mids)])
    T = np.stack([t[m - pre:m + post] for (_, t), m in zip(lst, mids)])
    qm = Q.mean(0); n = len(qm)
    print(f"{kind}: {len(lst)} cycles, {n / 500:.2f} s (lead-in {pre / 500:.2f} s), max spread between cycles {np.abs(Q - qm).max():.3f} rad, "
          f"peak |tau| hip/thigh/calf {np.abs(T).max((0, 1)).reshape(4, 3).max(0).round(1)} Nm", file=sys.stderr)
    out[kind] = qm; out[kind + "_tau"] = T.mean(0)
np.savez(args.npz, up=out["up"], down=out["down"], up_tau=out["up_tau"], down_tau=out["down_tau"], hz=500)


def keyframes(a):
    idx = np.unique(np.r_[np.arange(0, len(a), round(args.dt * 500)), len(a) - 1])
    return [round(i / 500, 3) for i in idx], [[round(float(v), 3) for v in a[i]] for i in idx]


KP = "[60, 80, 80, 60, 80, 80, 60, 80, 80, 60, 80, 80]"; KD = "[5, 4, 4, 5, 4, 4, 5, 4, 4, 5, 4, 4]"


def block(name, comment, transitions, kind, extra=""):
    """State_Fix block: keyframe 0 = the command at entry ([] -> lowcmd q, zero torque), then a --lead blend onto the
    recorded start pose, then the recorded motion with its torque as feed-forward (needs unitree_cpp_deploy-sport-replay.patch)"""
    ts, qs = keyframes(out[kind]); _, taus = keyframes(out[kind + "_tau"])
    ts = [0.0] + [round(args.lead + t, 3) for t in ts]; qs = [[]] + qs; taus = [[]] + taus
    if args.tail > 0: ts.append(round(ts[-1] + args.tail, 3)); qs.append(qs[-1]); taus.append(taus[-1])
    rows = lambda L: "".join(f"\n      {r}," for r in L)
    return (f"  {name}:   # {comment}\n    transitions: {transitions}\n{extra}"
            f"    kp: {KP}\n    kd: {KD}\n    gain_ramp_s: {args.ramp}\n    velocity_ff: true\n"
            f"    ts: {ts}\n    qs: [{rows(qs)}\n    ]\n    taus: [{rows(taus)}\n    ]\n")


n_up, n_dn = len(segs["up"]), len(segs["down"])
with open(args.out, "w") as f:
    f.write(f"  # --- generated by jetson/sport_motion_recorder/extract_keyframes.py from {n_up} sport-mode stand-ups / {n_dn} sit-downs"
            f" (keyframe dt {args.dt} s, lead-in {args.lead} s) ---\n")
    f.write(block("FixStand", "lying -> standing: replay of the original sport-mode StandUp",
                  "{Velocity: start.on_pressed, FixSquat: LT + A.on_pressed, Passive: LT + B.on_pressed}", "up"))
    f.write("\n" + block("FixSquat", "standing -> lying: replay of the original sport-mode StandDown, then Passive",
                         "{FixStand: LT + A.on_pressed, Passive: LT + B.on_pressed}", "down", "    auto_transition: Passive\n"))
print(f"wrote {args.out} and {args.npz}", file=sys.stderr)
